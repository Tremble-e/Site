-- ------------------------------------------------------------
-- 1. Tables
-- ------------------------------------------------------------
create table if not exists public.site_settings (
    id text primary key,
    content_initialized boolean not null default false,
    updated_at timestamptz not null default now()
);

insert into public.site_settings (id, content_initialized)
values ('main', false)
on conflict (id) do nothing;

create table if not exists public.site_admins (
    user_id uuid primary key references auth.users(id) on delete cascade,
    created_at timestamptz not null default now()
);

create table if not exists public.subjects (
    id text primary key,
    name text not null,
    icon text not null default 'fa-solid fa-book',
    sort_order integer not null default 0,
    is_published boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.documents (
    id bigint generated by default as identity primary key,
    subject_id text not null references public.subjects(id) on update cascade on delete restrict,
    type text not null check (type in ('lessons', 'exercises', 'sheets')),
    title text not null,
    url text not null,
    storage_path text,
    file_name text,
    sort_order integer not null default 0,
    is_published boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.info_blocks (
    id bigint generated by default as identity primary key,
    title text not null,
    text text not null,
    icon text not null default 'fa-solid fa-circle-info',
    image_url text,
    image_storage_path text,
    sort_order integer not null default 0,
    is_published boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.projects (
    id bigint generated by default as identity primary key,
    name text not null,
    description text not null default '',
    icon text not null default 'fa-solid fa-laptop-code',
    category text not null default 'application' check (category in ('application', 'tool', 'game')),
    status text not null default 'development' check (status in ('development', 'available', 'prototype', 'archived')),
    tags text[] not null default '{}',
    features text[] not null default '{}',
    logo_url text,
    logo_storage_path text,
    app_url text,
    dev_url text,
    sort_order integer not null default 0,
    is_published boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists documents_subject_idx on public.documents(subject_id);
create index if not exists documents_sort_idx on public.documents(subject_id, type, sort_order);
create index if not exists projects_sort_idx on public.projects(sort_order);
create index if not exists info_blocks_sort_idx on public.info_blocks(sort_order);

-- ------------------------------------------------------------
-- 2. Mise à jour automatique de updated_at
-- ------------------------------------------------------------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

drop trigger if exists trg_subjects_updated_at on public.subjects;
create trigger trg_subjects_updated_at before update on public.subjects
for each row execute function public.set_updated_at();

drop trigger if exists trg_documents_updated_at on public.documents;
create trigger trg_documents_updated_at before update on public.documents
for each row execute function public.set_updated_at();

drop trigger if exists trg_info_blocks_updated_at on public.info_blocks;
create trigger trg_info_blocks_updated_at before update on public.info_blocks
for each row execute function public.set_updated_at();

drop trigger if exists trg_projects_updated_at on public.projects;
create trigger trg_projects_updated_at before update on public.projects
for each row execute function public.set_updated_at();

drop trigger if exists trg_site_settings_updated_at on public.site_settings;
create trigger trg_site_settings_updated_at before update on public.site_settings
for each row execute function public.set_updated_at();

-- ------------------------------------------------------------
-- 3. Rôle administrateur
-- ------------------------------------------------------------
create or replace function public.is_site_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1
        from public.site_admins
        where user_id = auth.uid()
    );
$$;

grant execute on function public.is_site_admin() to anon, authenticated;

-- ------------------------------------------------------------
-- 4. Row Level Security
-- ------------------------------------------------------------
alter table public.site_settings enable row level security;
alter table public.site_admins enable row level security;
alter table public.subjects enable row level security;
alter table public.documents enable row level security;
alter table public.info_blocks enable row level security;
alter table public.projects enable row level security;

-- Settings
drop policy if exists "Public can read site settings" on public.site_settings;
create policy "Public can read site settings"
on public.site_settings for select
to anon, authenticated
using (true);

drop policy if exists "Admin can update site settings" on public.site_settings;
create policy "Admin can update site settings"
on public.site_settings for update
to authenticated
using (public.is_site_admin())
with check (public.is_site_admin());

-- Admins : un utilisateur authentifié ne peut voir que sa propre ligne.
drop policy if exists "Admin can read own membership" on public.site_admins;
create policy "Admin can read own membership"
on public.site_admins for select
to authenticated
using (user_id = auth.uid());

-- Subjects
