-- ============================================================
-- 6. À MODIFIER AVANT D'EXÉCUTER CETTE DERNIÈRE LIGNE
-- ============================================================
-- Remplacez VOTRE_UUID_ADMIN par l'UUID du compte créé dans
-- Authentication > Users, puis exécutez la ligne ci-dessous.
-- Exemple : 12345678-abcd-1234-abcd-1234567890ab

do $$
declare
    admin_uuid_text text := 'VOTRE_UUID_ADMIN';
begin
    if admin_uuid_text = 'VOTRE_UUID_ADMIN' then
        raise notice 'Compte admin non ajouté : remplacez VOTRE_UUID_ADMIN puis réexécutez ce bloc.';
    else
        insert into public.site_admins (user_id)
        values (admin_uuid_text::uuid)
        on conflict (user_id) do nothing;
    end if;
end $$;
